import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { notificationBrowser, waitOTP } from './project_catalog_browser_common.mjs';
import { assertNoCredentials, recordViewport } from './project_catalog_recording.mjs';

const app = fileURLToPath(new URL('../', import.meta.url));
await notificationBrowser(false, async ({ page, fixture, checks, evidence }) => {
  await page.goto(fixture.origin);
  await page.getByLabel('内部账号', { exact: true }).fill(fixture.alice.login);
  await page.getByLabel('密码', { exact: true }).fill(fixture.alice.password);
  await page.getByRole('button', { name: '登录工作空间', exact: true }).click();
  await page.getByLabel('六位验证码', { exact: true }).fill(await waitOTP(fixture));
  await page.getByRole('button', { name: '验证并继续', exact: true }).click();
  await page.getByRole('heading', { name: /工作从这里开始/ }).waitFor();
  await page.goto(fixture.origin + '/conversations/' + fixture.conversation_id);
  const planning = page.locator('section.panel').filter({ has: page.getByRole('heading', { name: '项目创建计划', exact: true }) });
  await planning.getByRole('button', { name: '拟定项目计划', exact: true }).click();
  const form = planning.locator('form');
  await form.getByLabel('项目名称', { exact: true }).fill('合成演示 · 项目交付');
  await form.getByLabel('项目范围', { exact: true }).fill('已核对负责人、成员、交付模板和计划日期。此项目仅为隔离演示。');
  await form.getByLabel('项目类型', { exact: true }).fill('delivery');
  await form.getByLabel('开始日期', { exact: true }).fill('2026-11-01');
  await form.getByLabel('截止日期', { exact: true }).fill('2026-11-30');
  await form.getByLabel('拟定原因', { exact: true }).fill('按已核对的人员及发布模板拟定准确计划。');
  await form.getByRole('button', { name: '选择人员目录', exact: true }).click();
  const candidate = id => form.locator('article').filter({ has: page.locator('code').filter({ hasText: new RegExp('^' + id + '$') }) });
  await candidate(fixture.owner_id).getByRole('button', { name: '设为负责人', exact: true }).click();
  await candidate(fixture.member_id).getByRole('button', { name: '加入项目成员', exact: true }).click();
  await form.getByRole('button', { name: '收起人员目录', exact: true }).click();
  await form.getByRole('button', { name: '选择模板目录', exact: true }).click();
  await candidate(fixture.template_id).getByRole('button', { name: '使用此模板', exact: true }).click();
  await form.getByRole('button', { name: '收起模板目录', exact: true }).click();
  await form.getByRole('button', { name: '核对准确目录内容', exact: true }).click();
  await form.locator('pre').filter({ hasText: '核对项目范围' }).waitFor();
  await form.getByRole('button', { name: '收起目录内容', exact: true }).click();
  const screenshots = [], prefix = 'project-catalog-web';
  async function shot(suffix, target) {
    await target.scrollIntoViewIfNeeded();
    await assertNoCredentials(page);
    assert.equal(await page.getByText(/PRIVATE_/).count(), 0);
    const file = 'docs/media/screenshots/' + prefix + '-' + suffix + '.png';
    await mkdir(path.dirname(path.join(app, '..', file)), { recursive: true });
    const bytes = await page.screenshot({ path: path.join(app, '..', file) });
    screenshots.push({ file, sha256: createHash('sha256').update(bytes).digest('hex') });
  }
  await shot('selection', form);
  checks.push('Actual Web selects an active non-self owner, an additional member and a published template; bounded template body, type and dates remain in the proposed intent.');
  const pending = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/v1/conversations/' + fixture.conversation_id + '/plans');
  await form.getByRole('button', { name: '保存待批准计划', exact: true }).click();
  const response = await pending; assert.equal(response.status(), 201);
  const proposed = (await response.json()).data;
  assert.equal(proposed.project.owner_id, fixture.owner_id);
  assert.deepEqual(proposed.project.member_ids, [fixture.member_id]);
  assert.equal(proposed.project.template_id, fixture.template_id);
  assert.equal(proposed.project.type, 'delivery');
  assert.equal(proposed.project.start_date, '2026-11-01');
  assert.equal(proposed.project.due_date, '2026-11-30');
  let card = planning.locator('article.conversation-source-preview').filter({ has: page.getByRole('heading', { name: '合成演示 · 项目交付 · 待本人批准', exact: true }) });
  await card.getByLabel('本次操作说明', { exact: true }).fill('本人已核对准确项目计划。');
  async function enabled(name) {
    await page.waitForFunction(n => [...document.querySelectorAll('button')].some(b => b.textContent === n && !b.disabled), name);
  }
  await enabled('批准这份准确计划');
  await shot('plan', card);
  let committed;
  const recording = await recordViewport(page, app, prefix, async () => {
    const approving = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/v1/plans/' + proposed.id + '/approve');
    await card.getByRole('button', { name: '批准这份准确计划', exact: true }).click();
    assert.equal((await approving).status(), 200);
    card = planning.locator('article.conversation-source-preview').filter({ has: page.getByRole('heading', { name: '合成演示 · 项目交付 · 已批准，等待创建', exact: true }) });
    await card.getByLabel('本次操作说明', { exact: true }).fill('按本人批准的模板、人员及日期创建项目。');
    await enabled('按已批准计划创建项目');
    const creating = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/v1/plans/' + proposed.id + '/commit');
    await card.getByRole('button', { name: '按已批准计划创建项目', exact: true }).click();
    const receipt = await creating; assert.equal(receipt.status(), 200); committed = (await receipt.json()).data;
    assert.equal(committed.id, proposed.id); assert.equal(committed.plan_hash, proposed.plan_hash);
    assert.equal(committed.state, 'committed'); assert.ok(committed.project_id); assert.ok(committed.operation_id);
    await planning.getByRole('link', { name: '打开已创建项目', exact: true }).waitFor();
    await planning.getByRole('link', { name: '打开已创建项目', exact: true }).scrollIntoViewIfNeeded();
  });
  const receipt = planning.locator('article.conversation-source-preview').filter({ has: page.getByRole('heading', { name: '合成演示 · 项目交付 · 项目已创建', exact: true }) });
  await shot('receipt', receipt);
  checks.push('An explicit human approval and separate creation action produce an actual committed project and stable operation receipt; template initialization is independently checked in native PG.');
  await page.reload();
  await planning.getByRole('link', { name: '打开已创建项目', exact: true }).waitFor();
  const after = await page.evaluate(async id => { const r = await fetch('/v1/plans/' + id); if (!r.ok) throw new Error('Plan readback failed'); return (await r.json()).data; }, proposed.id);
  assert.equal(after.state, 'committed'); assert.equal(after.project_id, committed.project_id); assert.equal(after.operation_id, committed.operation_id);
  assert.equal(after.project.owner_id, fixture.owner_id); assert.equal(after.template_snapshot.id, fixture.template_id);
  checks.push('Page reload and independent HTTP readback preserve the exact committed owner/template/operation; the fixture separately verifies dates and durable project initialization.');
  await writeFile(path.join(evidence, 'business-proof.json'), JSON.stringify({ plan_id: proposed.id, project_id: after.project_id, operation_id: after.operation_id, state: after.state, owner_id: after.project.owner_id, member_ids: after.project.member_ids, template_id: after.template_snapshot.id, dates: [after.project.start_date, after.project.due_date], durable_readback: true, model_contacted: false }, null, 2) + '\n');
  await writeFile(path.join(evidence, 'media.json'), JSON.stringify({ screenshots, recording, credentials_excluded: true, synthetic_data: true }, null, 2) + '\n');
}, 'project-catalog');
