  await page.getByRole('cell', { name: member.display_name, exact: true }).waitFor();
  checks.push('Project manager adds an active company member through the UI');
  await page.getByRole('tab', { name: '里程碑', exact: true }).click();
  await page.getByRole('button', { name: '新建里程碑', exact: true }).click();
  await page.getByLabel('里程碑名称').fill('可核验的首个节点');
