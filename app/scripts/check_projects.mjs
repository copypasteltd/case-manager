  await reason(page, '创建关联问题并保存', '浏览器验证：风险已发生');
  await page.getByText('已转问题', { exact: true }).waitFor();
  await page.getByRole('tab', { name: '问题', exact: true }).click();
  await page.getByRole('button', { name: '供应依赖需跟进', exact: true }).click();
