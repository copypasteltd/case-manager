  await page.getByRole('button', { name: '保存里程碑', exact: true }).click();
  await page.getByRole('cell', { name: '可核验的首个节点', exact: true }).waitFor();
  await page.getByRole('tab', { name: '任务', exact: true }).click();
  await page.getByRole('button', { name: '新建任务', exact: true }).first().click();
  await page.getByLabel('任务名称').fill('里程碑的完成证据');
  await page.getByLabel('负责人', { exact: true }).selectOption({ label: manager.display_name });
  await page.getByLabel('关联里程碑').selectOption({ label: '可核验的首个节点' });
  await page.getByRole('button', { name: '创建任务', exact: true }).click();
