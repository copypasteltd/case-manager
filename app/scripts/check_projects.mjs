  await page.getByRole('tab', { name: '成员', exact: true }).click();
  await page.getByRole('button', { name: '添加成员', exact: true }).click();
  await page.getByLabel('选择成员', { exact: true }).selectOption({ label: member.display_name });
  await page.getByLabel('变更原因', { exact: true }).fill('浏览器验证：加入协作成员');
