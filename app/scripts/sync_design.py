"""Copy reviewed design sources into app build inputs; docs remains authoritative."""
import json
import shutil
from pathlib import Path

APP=Path(__file__).resolve().parents[1]
SOURCE=APP.parent/'docs'/'design'
TARGET=APP/'packages'/'design'/'src'
TARGET.mkdir(parents=True,exist_ok=True)
for name in ('tokens.json','tokens.css'):
    shutil.copyfile(SOURCE/name,TARGET/name)
assets=APP/'web'/'public'/'brand'
assets.mkdir(parents=True,exist_ok=True)
for theme in ('light','dark'):
    shutil.copyfile(SOURCE/'assets'/('official-logo-'+theme+'.png'),assets/('logo-'+theme+'.png'))
mobile=APP/'mobile'/'src'
(mobile/'assets').mkdir(parents=True,exist_ok=True)
for theme in ('light','dark'):
    shutil.copyfile(SOURCE/'assets'/('official-logo-'+theme+'.png'),mobile/'assets'/('logo-'+theme+'.png'))
tokens=json.loads((SOURCE/'tokens.json').read_text(encoding='utf-8'))
rules=['/* Generated by scripts/sync_design.py from docs/design/tokens.json. */']
rules.append('.cp-page {')
rules.extend('  --cp-font-'+name+': '+value+';' for name,value in tokens['fontFamilies'].items())
rules.append('}')
for theme, values in tokens['themes'].items():
    rules.append('.cp-theme-'+theme+' {')
    rules.extend('  --cp-'+key.replace('.', '-')+': '+value+';' for key,value in values.items())
    rules.append('}')
(mobile/'tokens.css').write_text('\n'.join(rules)+'\n',encoding='utf-8')
print(json.dumps({'design_version':json.loads((SOURCE/'tokens.json').read_text(encoding='utf-8'))['meta']['version'],'synced':True}))
