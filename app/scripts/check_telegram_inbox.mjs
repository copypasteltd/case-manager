import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { notificationBrowser, waitOTP } from './telegram_inbox_browser_common.mjs';
import { assertNoCredentials, recordViewport } from './telegram_inbox_recording.mjs';
const app = fileURLToPath(new URL('../', import.meta.url));
await notificationBrowser(false, async ({ page, fixture, checks, evidence }) => {
  await page.goto(fixture.origin);
  await page.getByLabel('内部账号', { exact: true }).fill(fixture.alice.login);
  await page.getByLabel('密码', { exact: true }).fill(fixture.alice.password);
  await page.getByRole('button', { name: '登录工作空间', exact: true }).click();
  await page.getByLabel('六位验证码', { exact: true }).fill(await waitOTP(fixture));
  await page.getByRole('button', { name: '验证并继续', exact: true }).click();
  await page.getByRole('heading', { name: /工作从这里开始/ }).waitFor();
  await page.goto(fixture.origin + '/telegram?view=inbox');
  await page.getByRole('heading', { name: '入站请求台账', exact: true }).waitFor();
  const row = page.locator('[data-inbox-operation-id="' + fixture.request_id + '"]');
  await row.getByRole('button', { name: '查看入站详情', exact: true }).waitFor();
  const prefix = 'telegram-inbox-web', screenshots = [];
  async function shot(suffix) {
    await assertNoCredentials(page);
    assert.equal(await page.getByText(/PRIVATE_REQUEST_BODY|PRIVATE_OPERATOR_NOTE/).count(), 0);
    const file = 'docs/media/screenshots/' + prefix + '-' + suffix + '.png';
    await mkdir(path.dirname(path.join(app, '..', file)), { recursive: true });
    const bytes = await page.screenshot({ path: path.join(app, '..', file) });
    screenshots.push({ file, sha256: createHash('sha256').update(bytes).digest('hex') });
  }
  await shot('inventory');
  await row.getByRole('button', { name: '查看入站详情', exact: true }).click();
  const detail = page.locator('section.panel').filter({ has: page.getByRole('heading', { name: '入站详情与调度历史', exact: true }) });
  await detail.getByRole('button', { name: '撤回此排队请求', exact: true }).waitFor();
  await detail.scrollIntoViewIfNeeded();
  await shot('detail');
  checks.push('Authenticated organization inbox metadata and its actual acceptance journal are visible; request prose, private Telegram identity, binding proofs and model output are absent.');
  let receipt;
  const recording = await recordViewport(page, app, prefix, async () => {
    await detail.getByRole('button', { name: '撤回此排队请求', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '撤回尚未启动的TG请求', exact: true });
    await dialog.getByRole('checkbox', { name: '已核对准确请求并确认停止后续调度', exact: true }).check();
    await dialog.getByLabel('撤回原因', { exact: true }).fill('已核对合成请求，停止尚未启动的调度。');
    const pending = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/v1/telegram/inbox-operations/' + fixture.request_id + '/withdraw');
    await dialog.getByRole('button', { name: '确认撤回排队请求', exact: true }).click();
    const response = await pending;
    assert.equal(response.status(), 200);
    receipt = (await response.json()).data;
    assert.equal(receipt.state, 'withdrawn');
    assert.equal(receipt.run_id, null);
    assert.equal(receipt.version, 2);
    await dialog.waitFor({ state: 'hidden' });
    await detail.getByRole('heading', { name: /已撤回/ }).waitFor();
    assert.equal(await detail.getByRole('button', { name: '撤回此排队请求', exact: true }).count(), 0);
    await detail.scrollIntoViewIfNeeded();
  });
  await shot('receipt');
  checks.push('Explicit exact-request review and a recent human MFA session commit one pending withdrawal; no secretary task is created.');
  await page.reload();
  await page.locator('[data-inbox-operation-id="' + fixture.request_id + '"]').getByRole('button', { name: '查看入站详情', exact: true }).click();
  const after = await page.evaluate(async id => {
    const response = await fetch('/v1/telegram/inbox-operations/' + id);
    if (!response.ok) throw new Error('Durable inbox readback failed');
    return (await response.json()).data;
  }, fixture.request_id);
  assert.equal(after.item.state, 'withdrawn');
  assert.equal(after.item.version, receipt.version);
  assert.equal(after.item.withdrawable, false);
  assert.equal(after.item.run_id, null);
  assert.equal(after.history.items.length, 2);
  assert.equal(after.history.items[0].reason_code, 'manual_queue_withdrawn');
  assert.ok(after.history.items[0].actor_id);
  assert.equal(Object.hasOwn(after.history.items[0], 'reason'), false);
  checks.push('Reload and independent authenticated HTTP readback preserve the exact withdrawal and two journal revisions; the native fixture separately verifies one receipt/audit and zero run links.');
  await writeFile(path.join(evidence, 'business-proof.json'), JSON.stringify({ request_id: fixture.request_id, version: after.item.version, journal_events: after.history.items.length, manual_withdrawal: true, metadata_allowlist: true, durable_readback: true, secretary_run_created: false, bot_api_contacted: false, real_group: false }, null, 2) + '\n');
  await writeFile(path.join(evidence, 'media.json'), JSON.stringify({ screenshots, recording, credentials_excluded: true, synthetic_data: true }, null, 2) + '\n');
}, 'telegram-inbox');
